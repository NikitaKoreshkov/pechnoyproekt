async function main() {
  console.log('🔄 Обновление FAQ (печные комплексы, мангалы)...')

  const deleted = await prisma.fAQItem.deleteMany({})
  console.log(`🗑️ Удалено старых FAQ: ${deleted.count}`)

  for (const faq of FAQ_ITEMS) {
    await prisma.fAQItem.create({
      data: { id: randomUUID(), ...faq, updatedAt: new Date() },
    })
    console.log(`✅ ${faq.question.substring(0, 50)}...`)
  }

  console.log(`\n✅ Создано FAQ: ${FAQ_ITEMS.length}`)
  console.log('🎉 Готово!')
}

main()
  .catch((e) => {
    console.error('❌ Ошибка:', e)
    process.exit(1)
  })
  .finally(() => prisma.$disconnect())
